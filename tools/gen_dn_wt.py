"""DREADNOUGHT's factory wavetables (0.32): made here, put in the firmware as a C header, and kept in the repo as
Serum-format WAVs (wavetables/*.wav: 8 frames of 2048 samples, 16-bit, with Serum's clm chunk) so they open in Serum
too. Copyright (C) 2026 Jamie (TwistedGenetics).

    tools/gen_dn_wt.py OUT.h [--wavs DIR]

Each is 8 frames, made at 2048 samples a cycle, then put through tools/wt_convert.py as any Serum table would be.
"""
import math
import struct
import sys
from pathlib import Path

import numpy as np

sys.path.insert(0, str(Path(__file__).resolve().parent))
import wt_convert  # noqa: E402

N, F = 2048, 8
T = np.arange(N) / N


def additive(amps, phases=None):
    """a cycle from harmonic amplitudes amps[h-1] (sines, or the phases given)"""
    x = np.zeros(N)
    for h, a in enumerate(amps, 1):
        if a and h < N // 2:
            x += a * np.sin(2 * np.pi * h * T + (phases[h - 1] if phases is not None else 0.0))
    return x


def analog(i):                                      # sine -> triangle -> square -> saw
    u = i / (F - 1) * 3.0
    hs = np.arange(1, 128)
    sine = np.where(hs == 1, 1.0, 0.0)
    tri = np.where(hs % 2 == 1, (8 / np.pi ** 2) / hs ** 2 * np.where((hs // 2) % 2 == 0, 1, -1), 0.0)
    sq = np.where(hs % 2 == 1, (4 / np.pi) / hs, 0.0)
    saw = (2 / np.pi) / hs * np.where(hs % 2 == 1, 1, -1)
    sets = [sine, tri, sq, saw]
    k = min(int(u), 2)
    f = u - k
    return additive((1 - f) * sets[k] + f * sets[k + 1])


def reese(i):                                       # a saw with moving notches: two detuned saws, frozen at points
    d = 0.02 + 0.46 * i / (F - 1)
    hs = np.arange(1, 128)
    return additive(1.0 / hs * np.abs(np.cos(np.pi * hs * d)))


def ppg(i):                                         # digital: a band of harmonics stepping up, on a thin saw
    hs = np.arange(1, 128)
    c = 2 + i * 4
    band = np.exp(-((hs - c) / (1.5 + i * 0.2)) ** 2)
    return additive(0.25 / hs + band * (1.0 if i % 2 == 0 else -1.0))


def vocal(i):                                       # the vowels A E I O U, one into the next (formants on 110 Hz)
    V = [(800, 1150, 2900), (400, 1600, 2700), (350, 1700, 2700), (450, 800, 2830), (325, 700, 2530)]
    u = i / (F - 1) * 4.0
    k = min(int(u), 3)
    f = u - k
    fm = [(1 - f) * a + f * b for a, b in zip(V[k], V[k + 1])]
    hs = np.arange(1, 128)
    fr = hs * 110.0
    amp = sum(g * np.exp(-((fr - c) / w) ** 2) for c, g, w in zip(fm, (1.0, 0.6, 0.25), (90.0, 120.0, 180.0)))
    return additive(amp / np.sqrt(hs))


def sync(i):                                        # hard sync: a saw restarting each cycle, at 1x .. 8x
    r = 1.0 + 7.0 * i / (F - 1)
    p = (T * r) % 1.0
    return 2.0 * p - 1.0


def pwm(i):                                         # a pulse, 50 % .. 4 %
    w = 0.5 - 0.46 * i / (F - 1)
    return np.where(T < w, 1.0, -1.0)


def grit(i):                                        # a sine folded harder and harder
    g = 1.0 + 7.0 * i / (F - 1)
    return np.sin(np.pi / 2 * np.sin(2 * np.pi * T) * g)


def hollow(i):                                      # odd harmonics, drawbars moving: an organ going hollow
    hs = np.arange(1, 128)
    a = np.where(hs % 2 == 1, 1.0 / hs ** (1.5 - 0.9 * i / (F - 1)), 0.0)
    a += np.where((hs % 2 == 0) & (hs <= 8), 0.3 * i / (F - 1) / hs, 0.0)
    return additive(a)


TABLES = [("ANALOG", analog), ("REESE", reese), ("PPG", ppg), ("VOCAL", vocal), ("SYNC", sync), ("PWM", pwm),
          ("GRIT", grit), ("HOLLOW", hollow)]


def serum_wav(frames):
    """the frames (2048 each) as a Serum wavetable WAV: 16-bit mono 44.1 kHz with its clm chunk"""
    x = np.concatenate(frames)
    x = x / (np.max(np.abs(x)) or 1.0) * 0.95
    pcm = np.clip(np.floor(x * 32767 + 0.5), -32768, 32767).astype("<i2").tobytes()
    clm = b"<!>2048 10000000 wavetable (www.xferrecords.com)"
    fmt = struct.pack("<HHIIHH", 1, 1, 44100, 88200, 2, 16)
    body = b"WAVE" + b"fmt " + struct.pack("<I", 16) + fmt + b"clm " + struct.pack("<I", len(clm)) + clm + \
        b"data" + struct.pack("<I", len(pcm)) + pcm
    return b"RIFF" + struct.pack("<I", len(body)) + body


def main():
    out = Path(sys.argv[1])
    wavs = Path(sys.argv[sys.argv.index("--wavs") + 1]) if "--wavs" in sys.argv else None
    lines = ["/* generated by tools/gen_dn_wt.py: DREADNOUGHT's factory wavetables (src/dsp/dn_wt.h has the format) */",
             "#pragma once", "#include <stdint.h>", f"#define DN_WT_FACTORY {len(TABLES)}"]
    names = []
    for name, fn in TABLES:
        frames = [fn(i) for i in range(F)]
        if wavs:
            wavs.mkdir(parents=True, exist_ok=True)
            (wavs / f"{name.lower()}.wav").write_bytes(serum_wav(frames))
        x, clm = wt_convert.read_wav(serum_wav(frames))
        t = wt_convert.convert(x, clm=clm, name=name)
        sym = f"DN_WT_{name}"
        lines.append(f"static const uint8_t {sym}[{len(t)}] __attribute__((aligned(4))) = {{")
        for i in range(0, len(t), 24):
            lines.append("    " + ", ".join(str(v) for v in t[i:i + 24]) + ",")
        lines.append("};")
        names.append(sym)
    lines.append(f"static const uint8_t *const DN_WT_FACTORY_TABLES[DN_WT_FACTORY] = {{{', '.join(names)}}};")
    out.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
